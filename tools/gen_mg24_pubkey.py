#!/usr/bin/env python3
"""把 MG24 GBL 签名公钥（PEM）变成固件里的 64 字节 X||Y。

    python3 tools/gen_mg24_pubkey.py <pubkey.pem> <out.c>        # 生成 C 源文件
    python3 tools/gen_mg24_pubkey.py <pubkey.pem> --raw <out.bin> # 只写 64 字节裸点（测试用）

构建期由 components/ota_mgr/CMakeLists.txt 调用，输入是
mg24/release/mg24_gbl_signing_key.pub —— 那个 PEM 是公钥的**唯一正本**，
本脚本的输出是派生物，不入库。

为什么不依赖 `cryptography`：ESP-IDF 的 python 环境有它，但这个脚本也会被
主机侧测试和产线机器跑，少一个依赖少一种"环境不对"。P-256 未压缩公钥的
SubjectPublicKeyInfo 是**固定形状**：91 字节，前 27 字节是常量前缀
（SEQUENCE / ecPublicKey OID / prime256v1 OID / BIT STRING 头 / 0x04），
后 64 字节就是 X||Y。凡是不长这样的一律拒绝 —— 宁可构建失败，也不要把一把
错的钥匙悄悄编进固件。
"""

from __future__ import annotations

import base64
import hashlib
import sys
from pathlib import Path

# SubjectPublicKeyInfo prefix for an uncompressed secp256r1 public key
SPKI_P256_PREFIX = bytes.fromhex(
    "3059"                      # SEQUENCE, 89 bytes
    "3013"                      #   SEQUENCE, 19 bytes
    "06072a8648ce3d0201"        #     OID 1.2.840.10045.2.1 (ecPublicKey)
    "06082a8648ce3d030107"      #     OID 1.2.840.10045.3.1.7 (prime256v1)
    "0342 00"                   #   BIT STRING, 66 bytes, 0 unused bits
    "04"                        #   uncompressed point marker
    .replace(" ", "")
)
SPKI_P256_LEN = len(SPKI_P256_PREFIX) + 64   # 91

P256_P = 0xFFFFFFFF00000001000000000000000000000000FFFFFFFFFFFFFFFFFFFFFFFF
P256_B = 0x5AC635D8AA3A93E7B3EBBD55769886BC651D06B0CC53B0F63BCE3C3E27D2604B


def die(msg: str) -> None:
    sys.stderr.write(f"gen_mg24_pubkey: {msg}\n")
    sys.exit(1)


def load_xy(pem_path: Path) -> bytes:
    text = pem_path.read_text(encoding="ascii", errors="strict")
    lines = [ln.strip() for ln in text.splitlines() if ln.strip()]
    if len(lines) < 3 or lines[0] != "-----BEGIN PUBLIC KEY-----" or lines[-1] != "-----END PUBLIC KEY-----":
        die(f"{pem_path}: not a 'PUBLIC KEY' PEM (SubjectPublicKeyInfo)")
    try:
        der = base64.b64decode("".join(lines[1:-1]), validate=True)
    except Exception as e:  # noqa: BLE001
        die(f"{pem_path}: bad base64 ({e})")
    if len(der) != SPKI_P256_LEN or not der.startswith(SPKI_P256_PREFIX):
        die(f"{pem_path}: not an uncompressed secp256r1 public key ({len(der)} bytes)")
    xy = der[len(SPKI_P256_PREFIX):]
    x, y = int.from_bytes(xy[:32], "big"), int.from_bytes(xy[32:], "big")
    # on-curve check: y^2 == x^3 - 3x + b (mod p) — a typo'd key fails the build,
    # not the field.
    if x >= P256_P or y >= P256_P or (y * y - (x * x * x - 3 * x + P256_B)) % P256_P != 0:
        die(f"{pem_path}: point is not on secp256r1")
    return xy


def main(argv: list[str]) -> int:
    if len(argv) == 3 and argv[2] != "--raw":
        pem, out = Path(argv[1]), Path(argv[2])
        raw_out = None
    elif len(argv) == 4 and argv[2] == "--raw":
        pem, out, raw_out = Path(argv[1]), None, Path(argv[3])
    else:
        sys.stderr.write(__doc__)
        return 2

    xy = load_xy(pem)
    if raw_out is not None:
        raw_out.write_bytes(xy)
        return 0

    digest = hashlib.sha256(pem.read_bytes()).hexdigest()
    body = ", ".join(f"0x{b:02x}" for b in xy)
    rows = [body[i:i + 96].rstrip(", ") for i in range(0, len(body), 96)]
    text = (
        "/* GENERATED by tools/gen_mg24_pubkey.py -- do not edit.\n"
        f" * Source: {pem.as_posix()} (sha256 {digest})\n"
        " * ECDSA-P256 public key X||Y used by ota_mg24 to verify .gbl signatures. */\n"
        "#include <stdint.h>\n\n"
        "const uint8_t mg24_gbl_pubkey_xy[64] = {\n"
        + "".join(f"    {row},\n" for row in rows)
        + "};\n"
    )
    out.write_text(text, encoding="ascii")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
